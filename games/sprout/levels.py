LEVELS = [('MEADOW', MEADOW, 0x21), ('CAVERN', CAVERN, 0x0c), ('SUMMIT', SUMMIT, 0x27)]


def rows_of(segs):
    return [''.join(s[r] for s in segs) for r in range(13)]


if __name__ == '__main__':
    out = ['//! Sprout levels: 13 rows of metatiles, parsed at compile time into',
           '//! column-major data in switchable PRG banks. Generated by levels.py.',
           '']
    for i, (name, segs, sky) in enumerate(LEVELS):
        rows = rows_of(segs)
        width = len(rows[0])
        out.append(f'pub const W{i}: u16 = {width};')
        out.append(f'const TEXT{i}: [u8; _] = "')
        out.extend(rows)
        out.append('";')
        out.append(f'@bank({i}) pub const LEVEL{i}: [u8; 4096] = parse(TEXT{i}, {width});')
        out.append(f'pub const SPAWNS{i}: [u8; 64] = spawns(TEXT{i}, {width});')
        out.append('')
    out.append('pub const NAMES: [u8; _] = "%s";' % ''.join(n.ljust(8) for n, _, _ in LEVELS))
    out.append('pub const SKY: [u8; 3] = [%s];' % ', '.join(f'0x{s:02x}' for _, _, s in LEVELS))
    out.append(open('parse.nst').read())
    open('levels.nst', 'w').write('\n'.join(out) + '\n')
    for name, segs, _ in LEVELS:
        print(name, len(rows_of(segs)[0]))
